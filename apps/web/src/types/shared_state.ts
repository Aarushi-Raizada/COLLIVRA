// ============================================================================
// 1. Canonical URN Branded String Types
// ============================================================================

/**
 * URN for real catalogued orbital satellites and debris tracked by NORAD/CelesTrak.
 * Format: "catalog:norad:{1-6 digit noradCatId}" (e.g. "catalog:norad:25544")
 */
export type CatalogUrn = `catalog:norad:${string}`;

/**
 * URN for synthetic debris fragments generated by numerical breakup simulation.
 * Format: "synthetic:{scenarioId}:fragment:{fragId}" (e.g. "synthetic:SIM-001:fragment:042")
 */
export type SyntheticFragmentUrn = `synthetic:${string}:fragment:${string}`;

/**
 * URN for simulation scenarios (either collision-resistant UUIDs or stable benchmark fixtures).
 * Format: "scenario:{scenarioId}" (e.g. "scenario:SIM-a1b2c3d4-e5f6-47a8-b9c0-123456789abc")
 */
export type ScenarioUrn = `scenario:${string}`;

/**
 * URN for conjunction close-approach encounters identified during screening.
 * Format: "conjunction:{eventId}" (e.g. "conjunction:EVT-2026-001")
 */
export type ConjunctionUrn = `conjunction:${string}`;

/**
 * Union of all valid canonical URN types.
 */
export type CanonicalUrn =
  | CatalogUrn
  | SyntheticFragmentUrn
  | ScenarioUrn
  | ConjunctionUrn;

export type UrnKind = "CATALOG" | "SYNTHETIC" | "SCENARIO" | "CONJUNCTION";

