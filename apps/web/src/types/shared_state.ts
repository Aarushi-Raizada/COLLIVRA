/**
 * Context 2: Breakup Simulation Context
 * Governs synthetic fragmentation. Documents inherited vs independently supplied inputs.
 * Mass inputs are NEVER fabricated as catalog facts.
 */
export interface BreakupSimulationContext {
  /** Unique scenario URN */
  scenarioUrn: ScenarioUrn;
  /** Originating encounter if spawned from screening; null if manual or preset */
  sourceEventUrn: ConjunctionUrn | null;
  /** Collision epoch (inherited from encounter TCA or user supplied) */
  collisionEpochUtc: string;
  /** Parent Body A */
  parentA: {
    urn: CatalogUrn | SyntheticFragmentUrn;
    displayName: string;
    /** Inherited from encounter */
    positionGcrsKm: [number, number, number];
    velocityGcrsKms: [number, number, number];
    /** SUPPLIED SEPARATELY: Mass is NOT in public TLE/OMM data! */
    massKg: number;
    isMassEstimated: boolean;
    massProvenance: "USER_INPUT" | "SATELLITE_TEMPLATE" | "HISTORICAL_RECORD";
  };
  /** Parent Body B */
  parentB: {
    urn: CatalogUrn | SyntheticFragmentUrn;
    displayName: string;
    /** Inherited from encounter */
    positionGcrsKm: [number, number, number];
    velocityGcrsKms: [number, number, number];
    /** SUPPLIED SEPARATELY: Must be explicitly provided or configured */
    massKg: number;
    isMassEstimated: boolean;
    massProvenance: "USER_INPUT" | "DEBRIS_TEMPLATE" | "HISTORICAL_RECORD";
  };
  /** Fragmentation modeling parameters (Supplied separately) */
  fragmentationConfig: {
    fragmentCount: number;
    minFragmentMassKg: number;
    maxFragmentMassKg: number;
    vMedianKms: number;
    vSigma: number;
    maxDeltaVKms: number;
    powerLawExponent: number;
    seed: number | null;
  };
  /** Numerical propagation configuration (Supplied separately) */
  propagationConfig: {
    durationSeconds: number;
    stepSeconds: number;
    integrator: "DOP853";
  };
}

/**
 * Context 3: Clohessy-Wiltshire (CW) Remediation Context
 * Governs two-impulse rendezvous planning. Enforces near-circular preconditions.
 */
export interface CWRemediationContext {
  /** Unique scenario URN */
  scenarioUrn: ScenarioUrn;
  /** Inertial coordinate frame invariant (strictly GCRS) */
  coordinateFrame: "GCRS";
  /** Target orbital body URN */
  targetUrn: CatalogUrn | SyntheticFragmentUrn;
  targetEpochUtc: string;
  targetGcrsPositionKm: [number, number, number];
  targetGcrsVelocityKms: [number, number, number];
  /** Physical Preconditions (Must be asserted before CW solver dispatch) */
  targetEccentricity: number; // Enforce: e <= 0.005
  targetPerigeeKm: number;    // Enforce: rp >= 6478.137 km (Karman line boundary)
  /** Chaser spacecraft initial state (SUPPLIED SEPARATELY: Cannot be inherited) */
  chaserUrn: CatalogUrn | SyntheticFragmentUrn;
  chaserEpochUtc: string;
  chaserInitialGcrsPositionKm: [number, number, number];
  chaserInitialGcrsVelocityKms: [number, number, number];
  /** Remediation Maneuver Inputs (Supplied separately) */
  targetingMode: "STANDOFF_HOLD" | "CONTACT_INTERCEPT";
  standoffDistanceM: number;
  deltaVBudgetMaxMs: number;
  transferTimeSeconds: number;
}

