/**
 * Domain discriminator classifying scenario workflow types.
 */
export type ScenarioKind =
  | "BREAKUP_PROPAGATION"
  | "CW_REMEDIATION"
  | "COMPOSITE_BREAKUP_REMEDIATION";

/**
 * Base metadata shared by all heavy simulation result payloads.
 */
export interface BasePayloadMetadata {
  /** Unique payload identifier (RFC 4122 v4 UUID) */
  payloadId: string;
  /** Computation completion timestamp (ISO 8601 UTC) */
  computedAtUtc: string;
  /** Wall-clock execution time in milliseconds */
  executionWallTimeMs: number;
}

/**
 * Heavy numerical payload for synthetic collision breakup and DOP853 batch propagation.
 * Tier 3: Unreactive memory cache (STRICTLY EXCLUDED from Zustand store).
 */
export interface BreakupResultPayload extends BasePayloadMetadata {
  kind: "BREAKUP_PROPAGATION";
  breakupResponse: BreakupAndPropagateResponse;
  fragments: SyntheticFragmentRecord[];
  trajectories: FragmentTrajectory[];
  metadata: FragmentationMetadata;
}

/**
 * Heavy numerical payload for Clohessy-Wiltshire (CW) two-impulse rendezvous remediation.
 * Tier 3: Unreactive memory cache (STRICTLY EXCLUDED from Zustand store).
 */
export interface RemediationResultPayload extends BasePayloadMetadata {
  kind: "CW_REMEDIATION";
  remediationResponse?: BreakupRemediationResponse | null;
  chiefOrbit: {
    chief_gcrs_position_km: [number, number, number];
    chief_gcrs_velocity_kms: [number, number, number];
    semi_major_axis_km: number;
    mean_motion_rad_s: number;
    mu_earth_km3_s2?: number;
  };
  chaserState: {
    chaser_gcrs_position_km: [number, number, number];
    chaser_gcrs_velocity_kms: [number, number, number];
  };
  rendezvous: RendezvousResult;
}

/**
 * Heavy numerical payload for linked breakup and subsequent CW remediation.
 * Tier 3: Unreactive memory cache (STRICTLY EXCLUDED from Zustand store).
 */
export interface CompositeSimulationPayload extends BasePayloadMetadata {
  kind: "COMPOSITE_BREAKUP_REMEDIATION";
  breakupPayload: BreakupResultPayload;
  remediationPayload: RemediationResultPayload;
  selectedFragmentId: string;
}

/**
 * Authoritative Multi-Workflow Payload Record per Scenario.
 * Supports independent storage and invalidation of breakup and remediation results.
 * Tier 3: Unreactive memory cache (STRICTLY EXCLUDED from Zustand store).
 */
export interface ScenarioPayloadRecord {
  scenarioUrn: ScenarioUrn;
  version: number;
  createdAtUtc: string;
  updatedAtUtc: string;
  isBenchmarkFixture: boolean;

  /** Independently managed Breakup numerical payload */
  breakupPayload?: BreakupResultPayload | null;

  /** Independently managed CW Remediation numerical payload */
  remediationPayload?: RemediationResultPayload | null;

  /** Composite representation when both workflows are linked */
  compositePayload?: CompositeSimulationPayload | null;
}

