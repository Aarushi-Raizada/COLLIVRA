/**
 * Canonical reference to any physical orbital body (catalog payload, debris, or synthetic fragment).
 * Coordinates are strictly inertial GCRS.
 */
export interface CanonicalOrbitalObjectReference {
  /** Canonical URN */
  urn: CatalogUrn | SyntheticFragmentUrn;
  /** NORAD Catalog ID string if catalogued */
  noradCatId?: string;
  /** International designator (e.g. "1998-067A") */
  cosparId?: string;
  /** Human-readable designation */
  displayName: string;
  /** Physical classification */
  objectType: "PAYLOAD" | "ROCKET_BODY" | "DEBRIS" | "SYNTHETIC_FRAGMENT" | "UNKNOWN";
  /** True if produced by synthetic fragmentation model */
  isSynthetic: boolean;
  /** Epoch timestamp (ISO 8601 UTC) */
  epochUtc: string;
  /** Cartesian position in inertial GCRS frame [X, Y, Z] in kilometers */
  positionGcrsKm: [number, number, number];
  /** Cartesian velocity in inertial GCRS frame [Vx, Vy, Vz] in kilometers per second */
  velocityGcrsKms: [number, number, number];
  /** Physical mass in kg (null if unknown) */
  massKg: number | null;
  /** Approximate characteristic radius in meters */
  characteristicRadiusM?: number;
  /** Keplerian/mean elements if derived from TLE/OMM */
  orbitalElements?: {
    semiMajorAxisKm: number;
    eccentricity: number;
    inclinationDeg: number;
    raanDeg: number;
    argOfPericenterDeg: number;
    meanAnomalyDeg: number;
    periodMinutes?: number;
    periapsisAltitudeKm: number;
    apoapsisAltitudeKm: number;
  };
  /** Provenance tracking */
  provenance: {
    source: "CELESTRAK_OMM" | "LOCAL_FIXTURE" | "SYNTHETIC_SIMULATION";
    retrievedAtUtc: string;
    details?: string;
  };
}

